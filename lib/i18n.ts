export type TranslationKey = keyof typeof messages.th;

function formatTemplate(template: string, values?: TranslationValues) {
  if (!values) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (match, key) => {
    if (!(key in values)) {
      return match;
    }

    return String(values[key]);
  });
}

export function translate(
  language: AppLanguage,
  key: TranslationKey | string,
  values?: TranslationValues,
) {
  const dictionary = messages[language] as Record<string, string>;
  const fallbackDictionary = messages.th as Record<string, string>;
  const template = dictionary[key] || fallbackDictionary[key] || key;
  return formatTemplate(template, values);
}

export function createTranslator(language: AppLanguage) {
  return (key: TranslationKey | string, values?: TranslationValues) =>
    translate(language, key, values);
}